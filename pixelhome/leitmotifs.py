def _notes(key, transpose):
    return [(b, d, note(n) + transpose) for b, d, n in MOTIFS[key]['notes']]


def melody(key, transpose=0):
    """The top line: the highest note starting on each beat, [(beat, beats, midi)]."""
    top = {}
    for b, d, m in _notes(key, transpose):
        if b not in top or m > top[b][1]:
            top[b] = (d, m)
    return [(b, d, m) for b, (d, m) in sorted(top.items())]


def bass(key, transpose=0):
    """The bottom line: the lowest note starting on each beat."""
    low = {}
    for b, d, m in _notes(key, transpose):
        if b not in low or m < low[b][1]:
            low[b] = (d, m)
    return [(b, d, m) for b, (d, m) in sorted(low.items())]


def length(key):
    """Beats from the first note to the end of the last."""
    return max(b + d for b, d, _ in MOTIFS[key]['notes'])


def play(key, t0, beat, transpose=0, vel=100, line=None, legato=1.0):
    """Motif `key` from t0 seconds with a quarter note of `beat` seconds -> [(t, midi, vel, dur)].
    line: None for every note, 'melody' or 'bass' for that line only."""
    src = {'melody': melody, 'bass': bass}[line](key, transpose) if line else _notes(key, transpose)
    return [(t0 + b * beat, m, vel, d * beat * legato) for b, d, m in sorted(src)]

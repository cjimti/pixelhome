#!/usr/bin/env python3
"""Install (or update) Pixelhome Live's Pi side on an FPP player, over FPP's own API (no SSH).

    python3 live/install_pi.py [--fpp fpp.local] [--house cjimti] [--token-file ~/.config/pixelhome/live-token]

Uploads a one-shot install script to FPP's scripts folder and runs it with FPP's "Run Script" command (fppd
runs it as root). It puts pixelhome-live.py in /opt/pixelhome-live, writes the relay URL and token to
/home/fpp/media/config/pixelhome-live.json (readable only by fpp), adds a systemd service that starts at boot
and restarts if it stops, then deletes itself. Its log is /home/fpp/media/logs/pixelhome-live-install.log.

The token is the Worker's PUSH_TOKEN secret: the same file feeds `npx wrangler secret put PUSH_TOKEN < file`.
It is made here on first use and never printed.
"""
import argparse, base64, json, os, secrets, sys, time, urllib.parse, urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))

INSTALL = r'''#!/bin/bash
# Pixelhome Live installer (generated by live/install_pi.py, deletes itself when done)
LOG=/home/fpp/media/logs/pixelhome-live-install.log
exec > "$LOG" 2>&1
set -e
echo "start __RUN__ $(date)"
command -v python3 >/dev/null || { echo "FAILED: python3 not found"; exit 1; }
mkdir -p /opt/pixelhome-live
echo '__DAEMON__' | base64 -d > /opt/pixelhome-live/pixelhome-live.py
chmod 755 /opt/pixelhome-live/pixelhome-live.py
umask 077
echo '__CONF__' | base64 -d > /home/fpp/media/config/pixelhome-live.json
chown fpp:fpp /home/fpp/media/config/pixelhome-live.json
chmod 600 /home/fpp/media/config/pixelhome-live.json
umask 022
cat > /etc/systemd/system/pixelhome-live.service <<'UNIT'
[Unit]
Description=Pixelhome Live: tells live.pixelhome.app what the house is playing
After=network-online.target fppd.service
Wants=network-online.target

[Service]
User=fpp
ExecStart=/usr/bin/python3 /opt/pixelhome-live/pixelhome-live.py
Restart=always
RestartSec=10

[Install]
WantedBy=multi-user.target
UNIT
systemctl daemon-reload
systemctl enable pixelhome-live.service
systemctl restart pixelhome-live.service
sleep 3
systemctl is-active pixelhome-live.service
echo "OK $(date)"
rm -f "$0"
'''


def token(path):
    path = os.path.expanduser(path)
    if not os.path.exists(path):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, 'w') as f:
            f.write(secrets.token_urlsafe(32))
        print(f'made a new token in {path}; set it on the Worker: npx wrangler secret put PUSH_TOKEN < {path}')
    with open(path) as f:
        return f.read().strip()


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--fpp', default='fpp.local')
    ap.add_argument('--house', default='cjimti')
    ap.add_argument('--relay', default='https://live.pixelhome.app')
    ap.add_argument('--token-file', default='~/.config/pixelhome/live-token')
    a = ap.parse_args()
    b64 = lambda b: base64.b64encode(b).decode()
    daemon = open(os.path.join(HERE, 'pi', 'pixelhome-live.py'), 'rb').read()
    conf = json.dumps(dict(url=f'{a.relay}/push/{a.house}', token=token(a.token_file))).encode()
    run_id = secrets.token_hex(4)
    script = INSTALL.replace('__RUN__', run_id).replace('__DAEMON__', b64(daemon)).replace('__CONF__', b64(conf)).encode()
    api = f'http://{a.fpp}/api/'
    name = 'pixelhome-live-install.sh'
    urllib.request.urlopen(urllib.request.Request(api + 'file/scripts/' + name, data=script, method='POST'), timeout=30).read()
    run = dict(command='Run Script', args=[name, '', ''])
    urllib.request.urlopen(urllib.request.Request(api + 'command', data=json.dumps(run).encode(), method='POST',
                                                  headers={'Content-Type': 'application/json'}), timeout=30).read()
    log = api + 'file/logs/' + urllib.parse.quote('pixelhome-live-install.log')
    for _ in range(30):
        time.sleep(1)
        try:
            text = urllib.request.urlopen(log, timeout=5).read().decode()
        except Exception:
            continue
        if run_id not in text:          # still the previous run's log
            continue
        if 'OK ' in text or 'FAILED' in text or 'rror' in text:
            print(text.strip())
            sys.exit(0 if 'OK ' in text else 1)
    sys.exit('no result from the installer after 30 s; see the log on the player')


if __name__ == '__main__':
    main()
